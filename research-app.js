  var elFeed = document.getElementById('researchFeed');
  var elTabs = document.getElementById('researchTabs');

  var observer = ('IntersectionObserver' in window)
    ? new IntersectionObserver(function (entries) {
        entries.forEach(function (e) {
          if (e.isIntersecting) {
            e.target.classList.add('is-in');
            observer.unobserve(e.target);
          }
        });
      }, { rootMargin: '0px 0px -8% 0px', threshold: 0.06 })
    : null;

  function selectTab(id) {
    // elTabs.children now also holds the "|" separator spans between
    // buttons — skip anything without a dataset.tab rather than stamping
    // aria-selected onto a purely decorative, aria-hidden span.
    [].forEach.call(elTabs.children, function (b) {
      if (!b.dataset.tab) return;
      b.setAttribute('aria-selected', String(b.dataset.tab === id));
    });
    elFeed.innerHTML = '';
    hideTip();
    var tab = TABS.filter(function (t) { return t.id === id; })[0];
    if (!tab) return;
    tab.build().forEach(function (c) {
      elFeed.appendChild(c);
      if (observer) observer.observe(c);
      else c.classList.add('is-in');
    });
    try {
      history.replaceState(null, '', '#' + id);
    } catch (e) { /* file:// — harmless */ }
  }

  function renderStamp() {
    var span = R.time && R.time.yearRange;
    var set = function (id, v) {
      var n = document.getElementById(id);
      if (n) n.textContent = v;
    };
    set('rsTotal', fmt(R.metrics.total) + ' formations');
    set('rsWeek', R.week || '—');
    set('rsSpan', span ? span[0] + '–' + span[1] : '—');

    // Same scan stamp the other pages show, in the header chip and footer.
    // Shared formatter (shared-chrome.js) — see its header for why this is not
    // done inline any more.
    if (meta.lastScan && window.CCW) window.CCW.paintScanStamp(meta.lastScan);
  }

  function init() {
    if (!R) {
      elFeed.innerHTML =
        '<p class="r-reading">Research data hasn\'t been generated yet. Run ' +
        '<code>python3 analytics/export_research_json.py</code> to build ' +
        '<code>research.js</code>.</p>';
      return;
    }

    TABS.forEach(function (t, i) {
      // A separator between tabs, not inside one — keeping the "|" out of the
      // button means its hit area stays just the label, and the pipe can be
      // styled/hidden independently (it's aria-hidden, purely visual; the
      // tablist's own semantics carry the structure for assistive tech).
      if (i > 0) {
        var sep = h('span', 'research-tab-sep', '|');
        sep.setAttribute('aria-hidden', 'true');
        elTabs.appendChild(sep);
      }
      var b = h('button', 'research-tab', t.label);
      b.type = 'button';
      b.dataset.tab = t.id;
      b.setAttribute('role', 'tab');
      b.setAttribute('aria-selected', String(i === 0));
      b.addEventListener('click', function () { selectTab(t.id); });
      elTabs.appendChild(b);
    });

    renderStamp();

    var fromHash = (location.hash || '').replace('#', '');
    var initial = TABS.some(function (t) { return t.id === fromHash; }) ? fromHash : TABS[0].id;
    selectTab(initial);
  }

  init();
